const {chromium}=require("playwright"),assert=require("node:assert/strict"),path=require("node:path");
(async()=>{
const browser=await chromium.launch({channel:process.env.PLAYWRIGHT_BROWSER_CHANNEL||undefined,headless:true}),page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
const errors=[];page.on("pageerror",e=>errors.push(e.message));
const response=await page.goto("http://127.0.0.1:8765",{waitUntil:"networkidle"});assert.equal(response.status(),200);
await page.waitForFunction(()=>window.__xylem?.plan,{timeout:30000});
assert.equal(await page.locator("#error").isVisible(),false);
assert.equal(await page.evaluate(()=>__xylem.context.length),3186);
const verify=()=>page.evaluate(()=>{const m=__xylem;return m.plan.chosen.reduce((s,i)=>s+Math.ceil(m.plan.costs[i]/XylemOpt.UNIT)*XylemOpt.UNIT,0)<=m.params.budget*1e6;});
assert.equal(await verify(),true);
await page.screenshot({path:path.join(__dirname,"../preview-desktop.png"),fullPage:true});
const change=async(id,value)=>{await page.locator("#"+id).evaluate((el,value)=>{el.value=value;el.dispatchEvent(new Event("input",{bubbles:true}));},String(value));await page.waitForFunction(()=>document.querySelector("#plan-state").textContent.startsWith("Current"),{timeout:30000});};
await page.locator("#stress").click();await page.waitForFunction(()=>__xylem.uncertainty?.n===40,{timeout:60000});
assert.equal(await page.locator("#map-mode").inputValue(),"frequency");
await change("equity",2);
assert.equal(await page.evaluate(()=>__xylem.uncertainty),null);
await page.locator("#county").selectOption("Fresno");assert.match(await page.locator("#table-status").innerText(),/Fresno/);
const s=await page.evaluate(()=>__xylem.systems.find(s=>s.county==="Fresno"));
await page.locator("#search").fill(s.name+" · "+s.id);await page.locator("#search").dispatchEvent("change");
assert.match(await page.locator("#detail").innerText(),new RegExp(s.id));
await page.locator("#county").selectOption("");
await change("budget",0);assert.equal(await page.evaluate(()=>__xylem.plan.chosen.length),0);
await change("cost",2);await page.locator("#fund-all").click();
await page.waitForFunction(()=>document.querySelector("#plan-state").textContent.startsWith("Current"),{timeout:30000});
assert.equal(await page.evaluate(()=>__xylem.plan.chosen.length),1062);
assert.equal(await verify(),true);
await page.locator("#reset").click();await page.waitForFunction(()=>document.querySelector("#plan-state").textContent.startsWith("Current"));
const download=page.waitForEvent("download");await page.locator("#export").click();const d=await download;assert.equal(d.suggestedFilename(),"xylem-safer-plan.csv");
await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(__dirname,"../preview-mobile.png"),fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
assert.deepEqual(errors,[]);
console.log("Browser passed: map/data load, budget feasibility, current-scenario uncertainty, stale-result invalidation, county/search, zero budget, fund-all at doubled cost, CSV export, mobile overflow, no page errors.");
await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
